// Decodes one UTF-8 code point; advances *s. Invalid bytes become '?'.
static uint32_t next_cp(const char** s) {
    const unsigned char* p = (const unsigned char*)*s;
    uint32_t c = p[0];
    if (c < 0x80) { *s += 1; return c; }
    int extra = (c >= 0xF0) ? 3 : (c >= 0xE0) ? 2 : (c >= 0xC0) ? 1 : 0;
    if (extra == 0) { *s += 1; return '?'; }
    uint32_t cp = c & (0x3F >> extra);
    for (int i = 1; i <= extra; i++) {
        if ((p[i] & 0xC0) != 0x80) { *s += i; return '?'; }
        cp = (cp << 6) | (p[i] & 0x3F);
    }
    *s += extra + 1;
    return cp;
}

// Builds the 8 rows of the glyph for a code point (accented vowels are composed).
static void glyph_rows(uint32_t cp, uint8_t out[8]) {
    char base = 0;
    uint8_t acc0 = 0x06, acc1 = 0x0C; // grave accent
    switch (cp) {
        case 0xE0: base = 'a'; break;
        case 0xE8: base = 'e'; break;
        case 0xE9: base = 'e'; acc0 = 0x18; acc1 = 0x0C; break; // acute
        case 0xEC: base = 'i'; break;
        case 0xF2: base = 'o'; break;
        case 0xF9: base = 'u'; break;
        case 0xC0: base = 'A'; break;
        case 0xC8: base = 'E'; break;
        case 0xC9: base = 'E'; break;
        case 0xCC: base = 'I'; break;
        case 0xD2: base = 'O'; break;
        case 0xD9: base = 'U'; break;
        default: break;
    }
    if (base) {
        const uint8_t* g = GLYPHS[base - 32];
        for (int i = 0; i < 8; i++) out[i] = g[i];
        if (base >= 'a') { out[0] = acc0; out[1] = acc1; }  // lowercase: accent in the empty top rows
        return;                                             // uppercase: no room, plain letter
    }
    if (cp < 32 || cp > 126) cp = '?';
    const uint8_t* g = GLYPHS[cp - 32];
    for (int i = 0; i < 8; i++) out[i] = g[i];
}

void font_draw(Canvas& c, int x, int y, const char* text, uint32_t color, int scale) {
    if (!text) return;
    int cx = x;
    while (*text) {
        uint32_t cp = next_cp(&text);
        if (cp == '\n') { cx = x; y += FONT_CELL * scale + scale * 2; continue; }
        uint8_t rows[8];
        glyph_rows(cp, rows);
        for (int r = 0; r < 8; r++) {
            uint8_t bits = rows[r];
            if (!bits) continue;
            for (int b = 0; b < 8; b++)
                if (bits & (1 << b)) draw_rect(c, cx + b * scale, y + r * scale, scale, scale, color);
        }
        cx += FONT_CELL * scale;
    }
}

void font_draw_shadow(Canvas& c, int x, int y, const char* text, uint32_t color, int scale) {
    int off = scale > 1 ? scale / 2 + 1 : 1;
    font_draw(c, x + off, y + off, text, 0xFF000000u, scale);
    font_draw(c, x, y, text, color, scale);
}

int font_length(const char* text) {
    int n = 0;
    while (text && *text) { next_cp(&text); n++; }
    return n;
}

int font_width(const char* text, int scale) {
    return font_length(text) * FONT_CELL * scale;
}

void font_draw_centered(Canvas& c, int cx, int y, const char* text, uint32_t color, int scale) {
    font_draw_shadow(c, cx - font_width(text, scale) / 2, y, text, color, scale);
}
